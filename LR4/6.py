k = int(input())
if k < 0:
    print("Мы не находили грибы, а только теряли")
elif k % 100  > 9 and k % 100 < 20:
    print(f"Мы нашли в лесу {k} грибов ")
elif k % 10 == 1 :
    print(f"Мы нашли в лесу {k} гриб")
elif k% 10 == 2 or k % 10 == 3 or k % 10 == 4 :
    print(f"Мы нашли в лесу {k} гриба")
else:
    print(f"Мы нашли в лесу {k} грибов ")